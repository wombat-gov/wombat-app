export function getLocale() {
  const stored = String(getPreferences().locale ?? 'system').toLowerCase()
  const override = String(process.env.WOMBAT_LOCALE ?? '').trim().toLowerCase() || stored
  const requested = override && override !== 'system'
    ? override
    : String(app.getLocale() || 'en').toLowerCase()
  return requested.startsWith('de') ? 'de' : 'en'
}

function pseudo(messages) {
  if (process.env.WOMBAT_PSEUDO_LOCALE !== '1') return messages
  return Object.fromEntries(
    Object.entries(messages).map(([key, value]) => [key, `⟦${value}⟧`]),
  )
}

export function getMessages(locale = getLocale()) {
  return pseudo(MESSAGES[locale] ?? MESSAGES.en)
}

export function translate(locale, key) {
  return getMessages(locale)[key] ?? MESSAGES.en[key] ?? key
}

/** Current-locale lookup with {placeholder} interpolation. */
export function tt(key, fallback, vars = {}) {
  const template = getMessages()[key] ?? fallback ?? key
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`))
}

export function getI18nPayload() {
  return { locale: getLocale(), messages: getMessages() }
}

export function broadcastI18n() {
  const payload = getI18nPayload()
  for (const win of BrowserWindow.getAllWindows()) {
    if (win.isDestroyed()) continue
    try {
      win.webContents.send('shell:i18n', payload)
    } catch {
      /* window is going away */
    }
  }
  return payload
}

export function setLocalePreference(rawLocale, { persist = true } = {}) {
  const locale = ['system', 'en', 'de'].includes(String(rawLocale)) ? String(rawLocale) : 'system'
  if (persist) savePreferences({ locale })
  patchState({ ui: { locale: getLocale() } })
  broadcastI18n()
  return getI18nPayload()
}

let ipcRegistered = false

export function initI18n() {
  if (ipcRegistered) return
  ipcRegistered = true
  ipcMain.handle('shell:get-i18n', () => getI18nPayload())
  ipcMain.handle('shell:set-locale', (_event, locale, persist) => {
    const payload = setLocalePreference(locale, { persist: persist !== false })
    return { ok: true, ...payload }
  })
  patchState({ ui: { locale: getLocale() } })
}
